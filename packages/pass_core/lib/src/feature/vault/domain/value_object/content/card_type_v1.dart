import 'package:want_pass_core/src/feature/vault/domain/_barrel.dart';

enum CardTypeV1 {
  account,
  pat,
  rsa,
  ed25519,
  secretKey,
  passphrase,
  recoveryCodes,
  recoveryUrl,
  secretQa,
  vless,
  wireGuard,
  gpg,
  certificate,
  oauth,
  dsn,
  kubeconfig,
  webhookSecret,
  secureNote,
  file,
  apiKey,
  totp,
  awsIam,
  googleCloudKey,
  azureAppSecret,
  bearerToken,
  appPassword,
  sshCertificate,
  kubernetesToken,
  openVpn,
  ipsec,
  keyContainer,
  artifactSigningKey,
  apnsKey,
  appStoreConnectKey,
  registryAccess,
  environmentVariables,
  smtpAccess,
  presignedUrl,
  sessionCookie,
  hotp,
  licenseKey,
  wifi,
  devicePin,
  simPinPuk,
  paymentCard,
  bankDetails,
  identityDocument,
  walletMnemonic,
  walletPrivateKey,
  custom;

  bool get requiresAttachment => this == file || this == keyContainer;

  Set<FieldIdV1> get requiredFields => switch (this) {
    account => const {FieldIdV1.login, FieldIdV1.password},
    rsa || ed25519 || gpg => const {FieldIdV1.publicKey, FieldIdV1.privateKey},
    certificate => const {FieldIdV1.certificate, FieldIdV1.privateKey},
    oauth => const {FieldIdV1.clientId, FieldIdV1.clientSecret},
    secretQa => const {FieldIdV1.question, FieldIdV1.answer},
    recoveryCodes => const {FieldIdV1.recoveryCodes},
    file || custom => const {},
    apiKey => const {FieldIdV1.value},
    totp => const {FieldIdV1.totpSeed},
    awsIam => const {FieldIdV1.accessKeyId, FieldIdV1.value},
    googleCloudKey => const {FieldIdV1.jsonKey, FieldIdV1.project},
    azureAppSecret => const {
      FieldIdV1.tenantId,
      FieldIdV1.clientId,
      FieldIdV1.clientSecret,
    },
    bearerToken => const {FieldIdV1.value},
    appPassword => const {FieldIdV1.password},
    sshCertificate => const {FieldIdV1.certificate, FieldIdV1.privateKey},
    kubernetesToken => const {
      FieldIdV1.value,
      FieldIdV1.namespace,
      FieldIdV1.accountName,
    },
    openVpn => const {FieldIdV1.configuration},
    ipsec => const {FieldIdV1.identity},
    keyContainer => const {FieldIdV1.containerFormat, FieldIdV1.password},
    artifactSigningKey => const {FieldIdV1.privateKey, FieldIdV1.keyId},
    apnsKey => const {FieldIdV1.privateKey, FieldIdV1.keyId, FieldIdV1.teamId},
    appStoreConnectKey => const {
      FieldIdV1.privateKey,
      FieldIdV1.keyId,
      FieldIdV1.issuerId,
    },
    registryAccess => const {FieldIdV1.endpoint, FieldIdV1.login},
    environmentVariables => const {FieldIdV1.variables},
    smtpAccess => const {FieldIdV1.endpoint, FieldIdV1.login},
    presignedUrl => const {FieldIdV1.url, FieldIdV1.expiresAt},
    sessionCookie => const {
      FieldIdV1.domain,
      FieldIdV1.cookieName,
      FieldIdV1.value,
    },
    hotp => const {FieldIdV1.hotpSeed, FieldIdV1.counter},
    licenseKey => const {FieldIdV1.product, FieldIdV1.value},
    wifi => const {FieldIdV1.ssid, FieldIdV1.password},
    devicePin => const {FieldIdV1.device, FieldIdV1.pin},
    simPinPuk => const {FieldIdV1.carrier, FieldIdV1.pin, FieldIdV1.puk},
    paymentCard => const {
      FieldIdV1.cardNumber,
      FieldIdV1.holder,
      FieldIdV1.expiryMonth,
    },
    bankDetails => const {FieldIdV1.holder},
    identityDocument => const {
      FieldIdV1.documentType,
      FieldIdV1.documentNumber,
      FieldIdV1.authority,
    },
    walletMnemonic => const {FieldIdV1.mnemonic},
    walletPrivateKey => const {
      FieldIdV1.network,
      FieldIdV1.address,
      FieldIdV1.privateKey,
    },
    _ => const {FieldIdV1.value},
  };
  Set<FieldIdV1> get optionalFields => switch (this) {
    account => const {
      FieldIdV1.totpSeed,
      FieldIdV1.totpAlgorithm,
      FieldIdV1.totpDigits,
      FieldIdV1.totpPeriod,
      FieldIdV1.recoveryCodes,
      FieldIdV1.reserveLogins,
    },
    oauth => const {FieldIdV1.accessToken, FieldIdV1.refreshToken},
    pat => const {FieldIdV1.scopes, FieldIdV1.expiresAt},
    apiKey => const {FieldIdV1.keyId},
    totp => const {
      FieldIdV1.totpAlgorithm,
      FieldIdV1.totpDigits,
      FieldIdV1.totpPeriod,
    },
    awsIam => const {FieldIdV1.sessionToken},
    bearerToken => const {FieldIdV1.expiresAt},
    openVpn => const {FieldIdV1.privateKey, FieldIdV1.certificate},
    ipsec => const {FieldIdV1.value, FieldIdV1.certificate},
    registryAccess => const {FieldIdV1.password, FieldIdV1.accessToken},
    smtpAccess => const {FieldIdV1.password, FieldIdV1.accessToken},
    sessionCookie => const {FieldIdV1.expiresAt},
    licenseKey => const {FieldIdV1.expiresAt},
    bankDetails => const {
      FieldIdV1.iban,
      FieldIdV1.accountNumber,
      FieldIdV1.bic,
    },
    identityDocument => const {FieldIdV1.expiresAt},
    walletMnemonic => const {FieldIdV1.walletPassphrase},
    _ => const {},
  };
}
