"""Regenerate the vault bridge and enforce the package import boundary."""
import json
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parents[1]
assert subprocess.check_output(["flutter_rust_bridge_codegen", "--version"], text=True).strip() == "flutter_rust_bridge_codegen 2.13.0"
assert "flutter_rust_bridge: 2.13.0" in (root / "pubspec.yaml").read_text()
# The bridge dependency probe invokes FVM and can rewrite JSON whitespace.
sdk_config = root.parents[1] / ".fvmrc"
sdk_bytes = sdk_config.read_bytes()
try:
    subprocess.run(["flutter_rust_bridge_codegen", "generate", "--config-file", "flutter_rust_bridge.yaml", "--skip-fvm-install"], cwd=root, check=True)
finally:
    assert json.loads(sdk_config.read_bytes()) == json.loads(sdk_bytes), "Bridge tooling changed the pinned SDK configuration"
    if sdk_config.read_bytes() != sdk_bytes:
        sdk_config.write_bytes(sdk_bytes)
native = root / "lib/src/feature/vault/infrastructure/native"
barrel = "package:want_pass_core/src/feature/vault/infrastructure/_barrel.dart"
for path in [root / "rust/src/frb_generated.rs", *(native / name for name in ("api.dart", "api/v2.dart", "frb_generated.dart", "frb_generated.io.dart"))]:
    text = path.read_text()
    text = re.sub(r"(?m)^// (?:This file is automatically generated.*|@generated by.*)\n", "", text)
    if path.suffix == ".dart":
        text = re.sub(r"import '(?:\.\./)*(?:api(?:/v2)?|frb_generated(?:\.io)?)\.dart'(?:\s+if \(dart\.library\.js_interop\) 'frb_generated\.web\.dart')?;", "import '" + barrel + "';", text)
        found = False
        lines = []
        for line in text.splitlines():
            if line == "import '" + barrel + "';":
                if found:
                    continue
                found = True
            lines.append(line)
        text = "\n".join(lines) + "\n"
        text = re.sub(r"argValues: \[[^\]]*\]", "argValues: const []", text)
        assert "@generated by" not in text
        assert not re.search(r"import '(?:api|frb_generated)", text)
    path.write_text(text.lstrip())
subprocess.run(["fvm", "dart", "format", str(native)], cwd=root, check=True)
